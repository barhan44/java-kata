package dev.kata.concurrency;

import java.util.concurrent.Callable;
import java.util.concurrent.CompletableFuture;

/**
 * Kata 09. Последовательное выполнение задач по ключу (Actor / Kafka partition).
 *
 * <h2>Инженерный контекст</h2>
 *
 * <p>В обработчике событий задачи, относящиеся к одному {@code userId}/{@code orderId}, нельзя
 * выполнять параллельно: они меняют одно и то же состояние и должны идти строго в порядке
 * поступления. Задачи с разными ключами, наоборот, должны выполняться максимально параллельно —
 * иначе throughput падает до скорости одного ядра.
 *
 * <p>Это упрощённая модель Actor-а или partition consumer-а: у каждого ключа есть «почтовый ящик»,
 * который разбирает ровно один исполнитель, а разные ящики независимы.
 *
 * <h2>Требования</h2>
 *
 * <ol>
 *   <li>{@link #submit(Object, Callable)} возвращает future, завершающийся результатом задачи или
 *       её исключением (включая {@link java.util.concurrent.CompletionException} как обёртку).
 *   <li>Задачи с одинаковым ключом выполняются строго последовательно в порядке линеаризации {@code
 *       submit}. Порядок конкурентных вызовов определяется атомарностью операций над внутренней
 *       картой: каждый вызов получает своё место в очереди ключа.
 *   <li>Задачи с разными ключами выполняются параллельно.
 *   <li>Исключение в одной задаче не ломает цепочку: следующая задача того же ключа всё равно
 *       выполняется после завершения предыдущей.
 *   <li><b>Нет утечки памяти.</b> После выполнения последней задачи ключа запись удаляется из
 *       внутренней {@link java.util.concurrent.ConcurrentHashMap}. Миллионы уникальных ключей
 *       (например, UUID запросов) не должны навсегда оставлять миллионы пустых очередей.
 *   <li>{@link #activeKeyCount()} — диагностический счётчик ключей, для которых ещё есть задачи или
 *       идёт очистка. После завершения всех задач он должен вернуться к нулю.
 *   <li>{@link #close()} перестаёт принимать новые задачи и дожидается завершения уже принятых.
 *       Повторный вызов идемпотентен.
 * </ol>
 *
 * <h2>Главная гонка: удаление пустой очереди</h2>
 *
 * <p>Наивная схема «{@code computeIfAbsent} → положить задачу в очередь» ломается так:
 *
 * <pre>
 * submit(A) ----computeIfAbsent----> получил queue#1
 * drain(queue#1): очередь пуста, удаляю queue#1 из map
 * submit(A) -------------------------------------> queue#1.add(task)  // очередь уже никем не читается
 * submit(A) ----computeIfAbsent----> создал queue#2 и выполняет задачу параллельно
 * </pre>
 *
 * <p>Задача из queue#1 потеряна, а две задачи одного ключа выполняются одновременно. Поэтому
 * добавление задачи и удаление пустой очереди должны быть <b>одной атомарной операцией над
 * картой</b> (например, {@link java.util.concurrent.ConcurrentHashMap#compute}). Правильный
 * инвариант: удалять запись можно только если текущее значение карты — это именно наша очередь,
 * очередь пуста и её drain не активен. Тогда либо {@code submit} успевает добавить задачу (и
 * очередь перестаёт быть пустой), либо карта освобождается, и следующий {@code submit} создаёт
 * новую очередь.
 *
 * <h2>Сложность</h2>
 *
 * <ul>
 *   <li>{@code submit} — O(1) в среднем (плюс стоимость {@code compute} по бакету карты).
 *   <li>Память — O(ключей с непустыми очередями + задач в очередях), а не O(всех ключей за всё
 *       время.
 *   <li>Дополнительных потоков на ключ нет: drain занимает виртуальный поток только пока в очереди
 *       есть работа.
 * </ul>
 *
 * <h2>Граничные случаи</h2>
 *
 * <ul>
 *   <li>{@code key == null} или {@code task == null} — {@link NullPointerException}.
 *   <li>{@code submit} после {@code close} возвращает уже завершённый исключительно future с {@link
 *       java.util.concurrent.RejectedExecutionException}, а не бросает синхронно.
 *   <li>Задача вернула {@code null} — future успешно завершается {@code null}.
 *   <li>Задача бросила {@link Error} — future завершается исключительно, цепочка продолжается.
 *   <li>Одновременные {@code close} и {@code submit}: либо задача принята и выполнена, либо future
 *       завершается {@link java.util.concurrent.RejectedExecutionException}.
 * </ul>
 *
 * <p>Реализацию см. в {@code
 * dev.kata.solutions.concurrency.Kata09_KeyedSequentialExecutorSolution}. Тесты: {@code
 * Kata09_KeyedSequentialExecutorTest}.
 */
